"""Generate a VAPID key pair for Web Push and add it to backend/.env (only if not already set).

Usage (from backend/):  .venv/Scripts/python -m scripts.gen_vapid
"""

import base64
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from py_vapid import Vapid

ENV = Path(__file__).resolve().parents[1] / ".env"


def b64url(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def main() -> None:
    text = ENV.read_text(encoding="utf-8") if ENV.exists() else ""
    if "VAPID_PRIVATE_KEY=" in text and "VAPID_PRIVATE_KEY=\n" not in text and not text.rstrip().endswith("VAPID_PRIVATE_KEY="):
        print("VAPID keys already present in backend/.env - nothing to do.")
        return
    v = Vapid()
    v.generate_keys()
    private = b64url(v.private_key.private_numbers().private_value.to_bytes(32, "big"))
    public = b64url(v.public_key.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint))
    lines = [ln for ln in text.splitlines() if not ln.startswith(("VAPID_PUBLIC_KEY=", "VAPID_PRIVATE_KEY="))]
    lines += ["# Web Push (farmer alerts). Generated by scripts/gen_vapid.py - keep the private key secret.",
              f"VAPID_PUBLIC_KEY={public}", f"VAPID_PRIVATE_KEY={private}"]
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Added VAPID_PUBLIC_KEY and VAPID_PRIVATE_KEY to backend/.env")


if __name__ == "__main__":
    main()
