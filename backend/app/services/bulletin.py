"""GKMS-style agromet bulletin (PDF) for one block: block forecast, panchayat table, warnings, advisories.

English only for now: Telugu/Hindi PDF text needs complex-script shaping (planned).
"""

from __future__ import annotations

import io
from datetime import date as date_cls

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.core.imd import rain_category
from app.services import advisory as engine
from app.services.forecast import block_bundle, region, run_info
from app.services.profiles import resolve
from app.services.warnings import warnings_for_day

# Brand colours for print (must match --color-primary / --color-accent in theme.css)
PRIMARY = colors.HexColor("#0B5D4B")
ACCENT = colors.HexColor("#E8A317")
LIGHT = colors.HexColor("#EAF4F1")


def _t(data, widths, header_bg=PRIMARY):
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), header_bg), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#C9D6D2")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def build_pdf(ds, block_id: int) -> bytes:
    block, run, gps, bfc, pfc = block_bundle(ds, block_id)
    district = ds.get_district(block["district_id"])
    ri = run_info(run)
    ss = getSampleStyleSheet()
    h = ss["Heading1"].clone("h", textColor=PRIMARY, fontSize=16, spaceAfter=2)
    h2 = ss["Heading2"].clone("h2", textColor=PRIMARY, fontSize=11, spaceBefore=8, spaceAfter=4)
    small = ss["BodyText"].clone("s", fontSize=8, leading=10)
    body = ss["BodyText"].clone("b", fontSize=9, leading=11)
    days = sorted(bfc, key=lambda b: b["day"])
    wd = lambda iso: date_cls.fromisoformat(iso).strftime("%a %d %b")  # noqa: E731

    story = [
        Paragraph(f"Agromet Advisory Bulletin - {block['name']} block", h),
        Paragraph(f"{district['name'] if district else ''} district · Issued {ri['issued_at'][:16].replace('T', ' ')} IST · "
                  f"{ri['source_label']}", small),
        Paragraph("Panchayat-level values are downscaled from the block forecast and average back to it "
                  "(mass consistency). Generated by Kshetra.", small),
        Paragraph("Block forecast (IMD agromet bulletin fields)", h2),
        _t([["", *[wd(b["date"]) for b in days]],
            ["Rain (mm)", *[f"{b['rain_mm']:g} ({rain_category(b['rain_mm'])['label']})" for b in days]],
            ["Tmax / Tmin (°C)", *[f"{b['tmax']:g} / {b['tmin']:g}" for b in days]],
            ["RH max / min (%)", *[f"{b.get('rh_max') or '-'} / {b.get('rh_min') or '-'}" for b in days]],
            ["Wind (km/h)", *[f"{b['wind_kmh']:g}" for b in days]]], [30 * mm] + [30 * mm] * len(days)),
    ]

    names = {g["id"]: g for g in gps}
    warns = [w for r in pfc for w in warnings_for_day(r, names[r["panchayat_id"]], run) if w["level"] in ("orange", "red", "yellow")]
    if warns:
        story += [Paragraph("Warnings (IMD colour code)", h2),
                  _t([["Level", "Panchayat", "Day", "Hazard", "Value"]] +
                     [[w["level"].upper(), w["panchayat"]["name"], wd(w["date"]), w["title"]["en"].split(" · ")[1],
                       f"{w['value']} {w['unit']}"] for w in warns], [18 * mm, 45 * mm, 25 * mm, 45 * mm, 25 * mm], ACCENT)]

    by_gp: dict[int, dict[int, dict]] = {}
    for r in pfc:
        by_gp.setdefault(r["panchayat_id"], {})[r["day"]] = r
    rows = [["Panchayat", *[f"{wd(b['date'])}\nmm / °C" for b in days[:3]], "Conf.", "Top advisory (crop, stage)"]]
    saved = ds.get_crop_profiles()
    on = date_cls.fromisoformat(days[0]["date"])
    for g in sorted(gps, key=lambda g: g["name"]):
        d = by_gp.get(g["id"], {})
        prof = resolve(saved.get(g["id"]), g["id"], on)
        fc_days = [{**d[k], "weekday": ""} for k in sorted(d)]
        items = engine.evaluate(fc_days, prof["crop"], prof["stage"], d[1]["confidence"]) if d else []
        top = (f"{items[0]['title']['en']} ({prof['crop']}, {prof['stage_name']['en']})" if items else f"No action needed ({prof['crop']}, {prof['stage_name']['en']})")
        rows.append([g["name"], *[f"{d[k]['rain_mm']:g} / {d[k]['tmax']:g}" if k in d else "-" for k in (1, 2, 3)],
                     d[1]["confidence"].title() if d else "-", Paragraph(top, small)])
    story += [Paragraph(f"Panchayats ({len(gps)})", h2),
              _t(rows, [36 * mm, 22 * mm, 22 * mm, 22 * mm, 14 * mm, 64 * mm])]
    story += [Spacer(1, 6), Paragraph("Confidence: High / Medium / Low from agreement between forecast models. "
                                      "Advisories are rule-based; the extension officer approves before sending.", small)]

    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=14 * mm, rightMargin=14 * mm, topMargin=12 * mm, bottomMargin=12 * mm,
                      title=f"Agromet bulletin {block['name']}").build(story)
    return buf.getvalue()


__all__ = ["build_pdf", "region"]
